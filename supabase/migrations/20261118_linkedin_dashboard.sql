create table if not exists public.linkedin_dashboard_state (
  id text primary key check (id = 'default'),
  payload jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.linkedin_actions (
  id bigint generated by default as identity primary key,
  action_type text not null,
  payload jsonb not null,
  created_at timestamptz not null default now(),
  applied_at timestamptz
);

create index if not exists linkedin_actions_pending_idx
  on public.linkedin_actions (id)
  where applied_at is null;

alter table public.linkedin_dashboard_state enable row level security;
alter table public.linkedin_actions enable row level security;

revoke all on table public.linkedin_dashboard_state from anon, authenticated;
revoke all on table public.linkedin_actions from anon, authenticated;
